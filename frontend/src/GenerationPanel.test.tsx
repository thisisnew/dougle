import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, expect, it, vi } from 'vitest'
import GenerationPanel from './GenerationPanel'
import { request } from './api'

vi.mock('./api', () => ({ request: vi.fn() }))
const api = vi.mocked(request)
const preview = { provider: 'CODEX', expectedVersion: 1, digest: 'hash', prompt: '선택 근거만 전송', requestedModel: 'synthetic-model' }
beforeEach(() => { api.mockReset(); localStorage.clear() })

it('미리보기 후 건별 승인해야 작업 ID와 함께 생성을 요청한다', async () => {
  const user = userEvent.setup()
  const created = vi.fn()
  api.mockResolvedValueOnce(preview).mockResolvedValueOnce({ id: 'job', status: 'QUEUED' })
  render(<GenerationPanel base="/knowledge/one" disabled={false} onBusy={vi.fn()} onQueued={created} />)
  expect(api).not.toHaveBeenCalled()
  await user.click(screen.getByRole('button', { name: '전송 내용 미리보기' }))
  expect(await screen.findByLabelText('AI 전송 내용')).toHaveTextContent(preview.prompt)
  expect(screen.getByLabelText('요청 모델')).toHaveTextContent('synthetic-model')
  const generate = screen.getByRole('button', { name: '승인하고 별도 AI 초안 생성' })
  expect(generate).toBeDisabled()
  await user.click(screen.getByRole('checkbox'))
  await user.click(generate)
  await waitFor(() => expect(created).toHaveBeenCalledWith('job'))
  expect(api.mock.calls[1][0]).toBe('/knowledge/one/generation/jobs')
  expect(JSON.parse(api.mock.calls[1][1]!.body as string)).toEqual({ requestId: expect.any(String), provider: 'CODEX', requestedModel: 'synthetic-model', expectedVersion: 1, digest: 'hash', approved: true })
})

it('제공자를 바꾸면 이전 승인과 미리보기를 폐기한다', async () => {
  const user = userEvent.setup()
  api.mockResolvedValue(preview)
  render(<GenerationPanel base="/knowledge/one" disabled={false} onBusy={vi.fn()} onQueued={vi.fn()} />)
  await user.click(screen.getByRole('button', { name: '전송 내용 미리보기' }))
  await user.click(await screen.findByRole('checkbox'))
  await user.selectOptions(screen.getByRole('combobox', { name: 'AI 제공자' }), 'CLAUDE')
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
  expect(screen.queryByLabelText('AI 전송 내용')).not.toBeInTheDocument()
  expect(api).toHaveBeenCalledTimes(1)
})

it('접수 응답을 잃으면 자동 재전송하지 않고 같은 ID로 수동 재전송한다', async () => {
  const user = userEvent.setup()
  api.mockResolvedValueOnce(preview).mockRejectedValueOnce(new Error('응답 연결 끊김')).mockResolvedValueOnce({ id: 'same-job', status: 'RUNNING' })
  const created = vi.fn()
  render(<GenerationPanel base="/knowledge/one" disabled={false} onBusy={vi.fn()} onQueued={created} />)
  await user.click(screen.getByRole('button', { name: '전송 내용 미리보기' }))
  await user.click(await screen.findByRole('checkbox'))
  await user.click(screen.getByRole('button', { name: '승인하고 별도 AI 초안 생성' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('응답 연결 끊김')
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
  expect(created).not.toHaveBeenCalled()
  expect(api).toHaveBeenCalledTimes(2)
  expect(screen.getByRole('combobox', { name: '모델 선택 방식' })).toBeDisabled()
  await user.click(screen.getByRole('button', { name: '같은 요청 ID로 재전송' }))
  await waitFor(() => expect(created).toHaveBeenCalledWith('same-job'))
  expect(api.mock.calls[2][1]!.body).toBe(api.mock.calls[1][1]!.body)
})

it('모델을 수정하면 승인과 미리보기를 폐기하고 변경된 선택으로 미리본다', async () => {
  const user = userEvent.setup()
  api.mockResolvedValue(preview)
  render(<GenerationPanel base="/knowledge/one" disabled={false} onBusy={vi.fn()} onQueued={vi.fn()} />)
  await user.click(screen.getByRole('button', { name: '전송 내용 미리보기' }))
  await user.click(await screen.findByRole('checkbox'))
  await user.selectOptions(screen.getByRole('combobox', { name: '모델 선택 방식' }), 'custom')
  await user.type(screen.getByRole('textbox', { name: '모델 ID' }), 'chosen-model')
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
  expect(screen.queryByLabelText('AI 전송 내용')).not.toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: '전송 내용 미리보기' }))
  expect(JSON.parse(api.mock.calls[1][1]!.body as string)).toEqual({ provider: 'CODEX', requestedModel: 'chosen-model' })
  expect(await screen.findByRole('checkbox')).not.toBeChecked()
})

it('모델 선택은 제공자별로 저장하지만 전송 승인은 복원하지 않는다', async () => {
  const user = userEvent.setup()
  const view = render(<GenerationPanel base="/knowledge/one" disabled={false} onBusy={vi.fn()} onQueued={vi.fn()} />)
  await user.selectOptions(screen.getByRole('combobox', { name: '모델 선택 방식' }), 'custom')
  await user.type(screen.getByRole('textbox', { name: '모델 ID' }), 'saved-model')
  await user.click(screen.getByRole('button', { name: '이 브라우저에 모델 선택 저장' }))
  expect(screen.getByRole('status')).toHaveTextContent('전송 승인은 저장하지 않습니다')
  view.unmount()
  render(<GenerationPanel base="/knowledge/two" disabled={false} onBusy={vi.fn()} onQueued={vi.fn()} />)
  expect(screen.getByRole('textbox', { name: '모델 ID' })).toHaveValue('saved-model')
  expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
  await user.selectOptions(screen.getByRole('combobox', { name: 'AI 제공자' }), 'CLAUDE')
  expect(screen.getByRole('combobox', { name: '모델 선택 방식' })).toHaveValue('server')
  expect(api).not.toHaveBeenCalled()
})

it('직접 지정에서 빈 모델은 거절하고 CLI 기본 선택은 빈 문자열로 보낸다', async () => {
  const user = userEvent.setup()
  api.mockResolvedValue({ ...preview, requestedModel: '' })
  render(<GenerationPanel base="/knowledge/one" disabled={false} onBusy={vi.fn()} onQueued={vi.fn()} />)
  await user.selectOptions(screen.getByRole('combobox', { name: '모델 선택 방식' }), 'custom')
  await user.click(screen.getByRole('button', { name: '전송 내용 미리보기' }))
  expect(screen.getByRole('alert')).toHaveTextContent('모델 ID를 입력하세요')
  expect(api).not.toHaveBeenCalled()
  await user.selectOptions(screen.getByRole('combobox', { name: '모델 선택 방식' }), 'cli')
  await user.click(screen.getByRole('button', { name: '전송 내용 미리보기' }))
  expect(JSON.parse(api.mock.calls[0][1]!.body as string)).toEqual({ provider: 'CODEX', requestedModel: '' })
  expect(await screen.findByLabelText('요청 모델')).toHaveTextContent('CLI 기본값')
})
